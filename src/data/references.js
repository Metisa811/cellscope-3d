export function resolveOrganelleReferences(referenceLinks = []) {
  return referenceLinks.map((entry) => {
    const record = REFERENCES[entry.refId];
    if (!record) {
      return {
        id: entry.refId,
        title: `Unverified Reference (${entry.refId})`,
        authors: 'Authors not verified',
        journal: 'Unverified source',
        year: 'N/A',
        doi: null,
        url: null,
        verificationStatus: 'unverified',
        claimSupported: entry.claimSupported
      };
    }
    return {
      ...record,
      claimSupported: entry.claimSupported
    };
  });
}